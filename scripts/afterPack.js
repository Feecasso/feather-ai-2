'use strict';

/**
 * electron-builder afterPack hook.
 *
 * Keeps the packaged app honest: the generated artwork must be present, the
 * Windows executable must exist, and a small build manifest is written next to
 * app.asar so a USB copy can be traced back to the commit and target that built
 * it.
 */

const fs = require('node:fs');
const path = require('node:path');

function findAppRoot(appOutDir) {
  const candidates = [
    path.join(appOutDir, 'resources', 'app.asar'),
    path.join(appOutDir, 'resources', 'app')
  ];
  return candidates.find((candidate) => fs.existsSync(candidate)) || null;
}

exports.default = async function afterPack(context) {
  const appOutDir = context.appOutDir;
  const platform = context.electronPlatformName;
  const appRoot = findAppRoot(appOutDir);
  if (!appRoot) throw new Error(`afterPack: no packaged app found in ${appOutDir}`);

  const assetRoot = path.join(appOutDir, 'resources', 'assets');
  if (!fs.existsSync(assetRoot)) {
    // assets are inside app.asar; this only guards an unpacked layout.
    const unpacked = path.join(appOutDir, 'assets');
    if (!fs.existsSync(unpacked)) {
      console.warn('afterPack: assets are packed inside app.asar (expected for asar builds)');
    }
  }

  const exeName = platform === 'win32' ? 'FeatherAI.exe' : 'FeatherAI';
  if (platform === 'win32' && !fs.existsSync(path.join(appOutDir, exeName))) {
    throw new Error(`afterPack: ${exeName} is missing from ${appOutDir}`);
  }

  const manifest = {
    product: 'Feather AI 2.0',
    version: context.packager.appInfo.version,
    commit: process.env.GITHUB_SHA || process.env.FEATHER_BUILD_COMMIT || 'local',
    platform,
    arch: context.arch,
    builtAt: new Date().toISOString(),
    material: 'All artwork generated by scripts/generate-art.js'
  };
  fs.writeFileSync(
    path.join(appOutDir, 'resources', 'feather-build.json'),
    `${JSON.stringify(manifest, null, 2)}\n`,
    'utf8'
  );
  console.log(`afterPack: ${platform}/${context.arch} manifest written for ${exeName}`);
};
