'use strict';

const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..');
const SKIP_DIRS = new Set(['node_modules', 'release', 'usb', 'smoke', '.git', 'test', 'assets', 'build']);
const SECRET_PATTERNS = [
  { name: 'GitHub token', pattern: /\bgh[pousr]_[A-Za-z0-9]{30,}\b/ },
  { name: 'AWS access key', pattern: /\bAKIA[0-9A-Z]{16}\b/ },
  { name: 'OpenAI-style key', pattern: /\bsk-(?:proj-)?[A-Za-z0-9_-]{20,}\b/ },
  { name: 'Slack token', pattern: /\bxox[baprs]-[A-Za-z0-9-]{10,}\b/ },
  { name: 'private key block', pattern: /-----BEGIN (?:RSA |EC |OPENSSH )?PRIVATE KEY-----/ },
  { name: 'absolute developer home', pattern: /\/home\/feecasso\b/ }
];

function walk(dir, files = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.name.startsWith('.') && entry.name !== '.github') continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (!SKIP_DIRS.has(entry.name)) walk(full, files);
    } else if (/\.(js|json|md|txt|yml|yaml|html|css)$/i.test(entry.name)) {
      files.push(full);
    }
  }
  return files;
}

test('source, scripts, docs, and workflow files contain no obvious secrets or private paths', () => {
  const files = walk(ROOT);
  const findings = [];
  for (const file of files) {
    const text = fs.readFileSync(file, 'utf8');
    for (const { name, pattern } of SECRET_PATTERNS) {
      if (pattern.test(text)) findings.push(`${path.relative(ROOT, file)}: ${name}`);
    }
  }
  assert.deepEqual(findings, []);
});

test('no environment files or local key material are present in the workspace', () => {
  const forbidden = fs
    .readdirSync(ROOT)
    .filter((name) => /^\.env(\.|$)/i.test(name) || /\.(pem|key|pfx|p12)$/i.test(name));
  assert.deepEqual(forbidden, []);
});

test('every rendered image asset is generated by the art script', () => {
  const art = fs.readFileSync(path.join(ROOT, 'scripts', 'generate-art.js'), 'utf8');
  assert.match(art, /No third-party art/);
  assert.ok(fs.existsSync(path.join(ROOT, 'assets', 'sprites', 'agents.png')));
  assert.ok(fs.existsSync(path.join(ROOT, 'assets', 'icon-256.png')));
  assert.ok(fs.existsSync(path.join(ROOT, 'build', 'icon.ico')));
});
